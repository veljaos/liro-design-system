/**
 * fonts.css from the font packages' stylesheets: every @font-face keeps its unicode-range, so
 * a browser downloads a subset only when the page has a character in it. The files move from
 * ./files/ to ./fonts/. Returns the CSS and the file names it refers to.
 */
export function fontsCss(stylesheets: string[]): { css: string; files: string[] } {
  const files: string[] = []
  const faces = stylesheets
    .join('\n')
    .replace(/url\(\.\/files\/([^)]+)\)/g, (_match, file: string) => {
      files.push(file)
      return `url(./fonts/${file})`
    })
  if (/url\((?!\.\/fonts\/)/.test(faces)) {
    throw new Error('a font stylesheet refers to a file outside ./files/')
  }
  return {
    css: [
      HEADER,
      '/* Font faces of the Liro interface and brand faces (BUILD-PLAN P1.2), from Fontsource.',
      '   Licences: THIRD-PARTY-NOTICES.md (SIL Open Font License 1.1). */',
      faces.trim(),
      '',
    ].join('\n'),
    files,
  }
}

/**
 * The Tailwind v4 theme. Tailwind's own colours, radii, shadows, easings and breakpoints are
 * removed, so a raw colour such as bg-red-500 does not exist. Each meaning is exposed only to the
 * utilities it is meant for: text meanings to text-*, surfaces to bg-*, borders to border-* and
 * divide-*. So text-secondary is the secondary text colour, and bg-secondary is shadcn's.
 */
export function themeCss(): string {
  const reset = [
    '--color-*: initial;',
    '--radius-*: initial;',
    '--shadow-*: initial;',
    '--ease-*: initial;',
    '--breakpoint-*: initial;',
    '--font-*: initial;',
    '--font-weight-*: initial;',
    '--text-*: initial;',
    '--leading-*: initial;',
    '--tracking-*: initial;',
    '',
    '/* A.4 Breakpoints (literal: media queries cannot read variables) */',
    ...Object.entries(BREAKPOINTS).map(([name, value]) => `--breakpoint-${name}: ${value};`),
  ]

  const lines: string[] = ['/* A.2 Surfaces: bg-surface-page, bg-surface-raised, … */']
  for (const name of Object.keys(MEANINGS.surface)) {
    lines.push(`--background-color-surface-${kebab(name)}: var(--liro-surface-${kebab(name)});`)
  }
  lines.push('', '/* A.2 Text: text-primary, text-secondary, text-brand, text-link, … */')
  for (const name of Object.keys(MEANINGS.text)) {
    lines.push(`--text-color-${kebab(name)}: var(--liro-text-${kebab(name)});`)
  }
  lines.push(
    '',
    '/* A.2 Borders: border-default, border-strong, divide-subtle, … and focus rings */',
  )
  for (const name of Object.keys(MEANINGS.border)) {
    lines.push(`--border-color-${kebab(name)}: var(--liro-border-${kebab(name)});`)
  }
  lines.push('--outline-color-focus: var(--liro-border-focus);')
  // The control boundary also fills the parts that mark a control, such as the off track of a
  // switch (P2.1): bg-control.
  lines.push('--background-color-control: var(--liro-border-control);')
  lines.push('--ring-color-focus: var(--liro-border-focus);')
  lines.push('', '/* A.2 Brand: backgrounds, the text on them, and the accent */')
  for (const name of ['solid', 'solidHover', 'solidActive', 'subtle', 'subtleHover']) {
    lines.push(`--background-color-brand-${kebab(name)}: var(--liro-brand-${kebab(name)});`)
  }
  lines.push('--text-color-brand-on-solid: var(--liro-brand-on-solid);')
  lines.push('--color-brand-accent: var(--liro-brand-accent);')
  lines.push(
    '',
    '/* A.2 Status tones: text-status-danger-fg on bg-status-danger-bg, border-status-danger-border;',
    '   bg-/fill-/stroke-status-danger-solid for bars and dots, never for text (Appendix B.6). */',
  )
  for (const tone of Object.keys(TONES)) {
    const base = `--liro-status-${tone}`
    lines.push(`--text-color-status-${tone}-fg: var(${base}-fg);`)
    lines.push(`--background-color-status-${tone}-bg: var(${base}-bg);`)
    lines.push(`--border-color-status-${tone}-border: var(${base}-border);`)
    lines.push(`--background-color-status-${tone}-solid: var(${base}-solid);`)
    lines.push(`--fill-status-${tone}-solid: var(${base}-solid);`)
    lines.push(`--stroke-status-${tone}-solid: var(${base}-solid);`)
  }
  lines.push(
    '',
    '/* A.6 Families, for buttons: bg-family-destructive-solid (hover, active), text-on-accent on it;',
    '   bg-family-destructive-subtle (hover) with text-family-destructive-fg. */',
  )
  for (const [family, parts] of Object.entries(FAMILIES)) {
    const base = `--liro-family-${family}`
    for (const part of ['solid', 'solidHover', 'solidActive', 'subtle', 'subtleHover']) {
      if (part in parts) {
        lines.push(
          `--background-color-family-${family}-${kebab(part)}: var(${base}-${kebab(part)});`,
        )
      }
    }
    lines.push(`--text-color-family-${family}-fg: var(${base}-fg);`)
    lines.push(`--text-color-family-${family}-fg-hover: var(${base}-fg-hover);`)
  }
  lines.push('', '/* A.3 Radius (rounded-none and rounded-full are built in) and shadows */')
  for (const name of ['xs', 'sm', 'md', 'lg', 'xl']) {
    lines.push(`--radius-${name}: var(--liro-radius-${name});`)
  }
  for (const name of Object.keys(SHADOWS)) {
    lines.push(`--shadow-${name}: var(--liro-shadow-${name});`)
  }
  lines.push(
    '',
    '/* A.4 Motion: ease-standard, …; the default transition uses base and standard */',
  )
  for (const name of Object.keys(EASING)) {
    lines.push(`--ease-${name}: var(--liro-ease-${name});`)
  }
  lines.push('--default-transition-duration: var(--liro-duration-base);')
  lines.push('--default-transition-timing-function: var(--liro-ease-standard);')
  lines.push('', '/* A.4 Sizes: h-header, h-control, h-control-sm, max-w-content */')
  lines.push('--spacing-header: var(--liro-size-header-height);')
  lines.push('--spacing-control: var(--liro-size-control-height);')
  lines.push('--spacing-control-sm: var(--liro-size-control-height-sm);')
  lines.push('--container-content: var(--liro-size-content-max-width);')
  lines.push(
    '',
    '/* A.5 Typography: font-sans, font-brand, font-mono; text-xs … text-xl with the body line',
    '   height and letter spacing of the script; text-h1 … text-h6; font-regular … font-bold;',
    '   leading-tight|base|relaxed; tracking-heading|body|caps. Tabular digits: tabular-nums. */',
  )
  lines.push('--font-sans: var(--liro-font-sans);')
  lines.push('--font-brand: var(--liro-font-brand);')
  lines.push('--font-mono: var(--liro-font-mono);')
  lines.push('--default-font-family: var(--liro-font-sans);')
  lines.push('--default-mono-font-family: var(--liro-font-mono);')
  for (const name of Object.keys(FONT_SIZE)) {
    lines.push(`--text-${name}: var(--liro-font-size-${name});`)
    lines.push(`--text-${name}--line-height: var(--liro-leading-body);`)
    lines.push(`--text-${name}--letter-spacing: var(--liro-tracking-body-text);`)
  }
  for (const level of Object.keys(HEADINGS)) {
    const n = level.slice(1)
    lines.push(`--text-${level}: var(--liro-heading-${n}-size);`)
    lines.push(`--text-${level}--line-height: var(--liro-heading-${n}-line-height);`)
    lines.push(`--text-${level}--font-weight: var(--liro-font-weight-semibold);`)
    lines.push(`--text-${level}--letter-spacing: var(--liro-tracking-heading-text);`)
  }
  for (const name of Object.keys(FONT_WEIGHT)) {
    lines.push(`--font-weight-${name}: var(--liro-font-weight-${name});`)
  }
  for (const name of Object.keys(LEADING)) {
    lines.push(`--leading-${name}: var(--liro-leading-${name});`)
  }
  for (const name of Object.keys(TRACKING)) {
    lines.push(`--tracking-${name}: var(--liro-tracking-${name});`)
  }
  lines.push(
    '',
    '/* shadcn/ui names, for the copied primitives only (bg-background, text-muted-foreground, …).',
    '   text-destructive is the danger text colour, readable on surfaces. */',
  )
  for (const name of Object.keys(SHADCN)) {
    if (name !== 'radius') lines.push(`--color-${name}: var(--${name});`)
  }
  lines.push('--text-color-destructive: var(--liro-status-danger-fg);')

  return [
    HEADER,
    '/*',
    ' * Tailwind v4 theme: semantic utility names that read the --liro-* variables of tokens.css.',
    ' * `inline` makes utilities reference the variables directly, so each theme resolves on its own',
    ' * element. Import after tailwindcss: @import "tailwindcss"; @import "@veljaos/tokens/theme.css";',
    ' */',
    block('@theme', reset),
    '',
    block('@theme inline', lines),
    '',
  ].join('\n')
}

export function tokensJson(): string {
  return `${JSON.stringify(resolvedTokens(), null, 2)}\n`
}
