/** A meaning's value in CSS: a value reference becomes var(--liro-…), a literal stays. */
function cssValue(reference: string): string {
  const variable = valueVariable(reference)
  return variable === null ? reference : `var(${variable})`
}

function block(selector: string, lines: string[]): string {
  return `${selector} {\n${lines.map((line) => (line === '' ? '' : `  ${line}`)).join('\n')}\n}`
}

